/* This array is TWO vendor FSBL tables concatenated by the recovery tool. Only
 * the first runs: ps7_config() returns at the FIRST EMIT_EXIT()
 * (arch/arm/mach-zynq/ps7_spl_init.c:98), so the three 0xC5ACCE55 CoreSight
 * lock-access writes below are DEAD CODE and have never executed on this board.
 * Left byte-for-byte as recovered -- enabling them would be a behaviour change
 * that nothing here needs. Do not "fix" it by deleting the first EMIT_EXIT().
 *
 * The LVL_SHFTR_EN / FPGA_RST_CTRL pair that used to sit between the SLCR
 * unlock and lock below moved to ps7_postconfig_3_0[] -- see the comment there.
 * What remains is the bare SLCR unlock/lock bracket, which is a no-op; it is
 * kept so the recovered table structure still lines up with the FSBL dump. */
unsigned long ps7_preconfig_3_0[] = {
	EMIT_WRITE(0xF8000008U, 0x0000DF0DU),
	EMIT_WRITE(0xF8000004U, 0x0000767BU),
	EMIT_EXIT(),
	EMIT_WRITE(0xF8898FB0U, 0xC5ACCE55U),
	EMIT_WRITE(0xF8899FB0U, 0xC5ACCE55U),
	EMIT_WRITE(0xF8809FB0U, 0xC5ACCE55U),
	EMIT_EXIT(),
};

/* Vendor FSBL post-config table, found three times (once per silicon rev) at
 * FSBL offsets 0x0ee4c / 0x0ee88 / 0x0eec4:
 *   MASKWRITE 0xF8000900 mask=0x0000000F val=0x0000000F   LVL_SHFTR_EN  = 0xF
 *   MASKWRITE 0xF8000240 mask=0xFFFFFFFF val=0x00000000   FPGA_RST_CTRL = 0
 * We carried these in ps7_preconfig_3_0[] instead, i.e. we raised the PS<->PL
 * level shifters and released the four PL AXI resets at the very top of SPL,
 * before MIO/PLL/clock/DDR, where the vendor does it at the end. Same two
 * writes, same values, wrong place.
 *
 * The SLCR unlock/lock bracket is repeated here because U-Boot expects the SLCR
 * to be LOCKED between accesses (arch/arm/mach-zynq/cpu.c:54,74 and
 * drivers/clk/clk_zynq.c:343,345 each unlock, write, re-lock), so this table
 * must leave it locked exactly as the pre-config table did. */
unsigned long ps7_postconfig_3_0[] = {
	EMIT_WRITE(0xF8000008U, 0x0000DF0DU),
	EMIT_MASKWRITE(0xF8000900U, 0x0000000FU, 0x0000000FU),
	EMIT_MASKWRITE(0xF8000240U, 0xFFFFFFFFU, 0x00000000U),
	EMIT_WRITE(0xF8000004U, 0x0000767BU),
	EMIT_EXIT(),
};

int ps7_init(void)
{
	int ret;
	ret = ps7_config(ps7_preconfig_3_0);      if (ret != PS7_INIT_SUCCESS) return ret;
	ret = ps7_config(ps7_mio_init_data_3_0);   if (ret != PS7_INIT_SUCCESS) return ret;
	ret = ps7_config(ps7_pll_init_data_3_0);   if (ret != PS7_INIT_SUCCESS) return ret;
	ret = ps7_config(ps7_clock_init_data_3_0); if (ret != PS7_INIT_SUCCESS) return ret;
	ret = ps7_config(ps7_ddr_init_data_3_0);   if (ret != PS7_INIT_SUCCESS) return ret;
	ret = ps7_config(ps7_peripheral_init_data_3_0); if (ret != PS7_INIT_SUCCESS) return ret;
	return PS7_INIT_SUCCESS;
}

/* Called unconditionally at the end of SPL, from spl_board_prepare_for_boot()
 * (arch/arm/mach-zynq/spl.c:87) which common/spl/spl.c:841 invokes just before
 * jump_to_image(). It is NOT gated on a bitstream having been loaded, so moving
 * the two writes here does not risk dropping them: they still run on every boot,
 * just after the FIT load instead of before DDR init. The state handed to U-Boot
 * proper -- and therefore to Linux -- is byte-identical to before. */
int ps7_post_config(void)
{
	return ps7_config(ps7_postconfig_3_0);
}
int ps7_debug(void) { return PS7_INIT_SUCCESS; }
